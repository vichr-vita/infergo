func commandFixture(t *testing.T) {
	t.Helper()
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	t.Chdir(t.TempDir())
	clearEnvironment(t)
	t.Setenv("GOWORK", "off")
	write(t, "go.mod", fmt.Sprintf("module example.com/rules\n\ngo 1.26.0\n\nrequire github.com/vichr-vita/infergo v0.0.0\nreplace github.com/vichr-vita/infergo => %q\n", root))
	write(t, "rules.go", `package rules
type Inputs struct { Seed int `+"`fact:\"seed\"`"+` }
type Outputs struct { Value int `+"`fact:\"value\"`"+` }
type CustomInputs = Inputs
type CustomOutputs = Outputs
func Step(seed int) (middle int) { return seed + 1 }
`)
	write(t, "extra.go", `package rules
func Finish(middle int) (value int) { return middle + 1 }
`)
}

func clearEnvironment(t *testing.T) {
	t.Helper()
	for _, key := range []string{"CONFIG", "RULES", "INPUTS", "OUTPUTS", "OUT", "CHECK", "HTML", "OPEN"} {
		t.Setenv("INFERGEN_"+key, "")
	}
}

func mustRead(t *testing.T, path string) string {
	t.Helper()
	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(content)
}

func write(t *testing.T, path, source string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestCommandGeneration(t *testing.T) {
	tests := []struct {
		name            string
		args            []string
		configFile      string
		config          string
		env             map[string]string
		out             string
		inputs, outputs string
	}{
		{
			name: "flags with defaults",
			args: []string{"--rules", "rules.go, extra.go"},
		},
		{
			name: "repeated rule flags",
			args: []string{"--rules", "rules.go", "--rules", "extra.go"},
		},
		{
			name:       "automatic config discovery",
			configFile: "infergen.yaml",
			config:     "rules: [rules.go, extra.go]\ninputs: CustomInputs\noutputs: CustomOutputs\nout: configured.go\n",
			out:        "configured.go",
			inputs:     "CustomInputs",
			outputs:    "CustomOutputs",
		},
		{
			name:       "explicit config outside the ruleset",
			args:       []string{"--config", "config/settings.json"},
			configFile: "config/settings.json",
			config:     `{"rules": ["rules.go", "extra.go"], "out": "configured.go"}`,
			out:        "configured.go",
		},
		{
			name:       "environment overrides config",
			configFile: "settings.toml",
			config:     "rules = ['missing.go']\ninputs = 'MissingInputs'\noutputs = 'MissingOutputs'\nout = 'missing/output.go'\n",
			env: map[string]string{
				"CONFIG": "settings.toml", "RULES": "rules.go, extra.go",
				"INPUTS": "CustomInputs", "OUTPUTS": "CustomOutputs", "OUT": "environment.go",
			},
			out:     "environment.go",
			inputs:  "CustomInputs",
			outputs: "CustomOutputs",
		},
		{
			name:       "flags override environment and config",
			args:       []string{"--config", "settings.yaml", "--rules", "rules.go,extra.go", "--inputs", "CustomInputs", "--outputs", "CustomOutputs", "--out", "flags.go"},
			configFile: "settings.yaml",
			config:     "rules: [missing.go]\ninputs: MissingInputs\noutputs: MissingOutputs\nout: missing/output.go\n",
			env: map[string]string{
				"CONFIG": "missing.yaml", "RULES": "missing.go",
				"INPUTS": "MissingInputs", "OUTPUTS": "MissingOutputs", "OUT": "missing/output.go",
			},
			out:     "flags.go",
			inputs:  "CustomInputs",
			outputs: "CustomOutputs",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			commandFixture(t)
			if test.configFile != "" {
				if err := os.MkdirAll(filepath.Dir(test.configFile), 0o755); err != nil {
					t.Fatal(err)
				}
				write(t, test.configFile, test.config)
			}
			for key, value := range test.env {
				t.Setenv("INFERGEN_"+key, value)
			}
			command := newCommand()
			command.SetArgs(append([]string{}, test.args...))
			if err := command.Execute(); err != nil {
				t.Fatal(err)
			}
			out := test.out
			if out == "" {
				out = "zz_infergo_gen.go"
			}
			source, err := os.ReadFile(out)
			if err != nil {
				t.Fatal(err)
			}
			inputs, outputs := test.inputs, test.outputs
			if inputs == "" {
				inputs = "Inputs"
			}
			if outputs == "" {
				outputs = "Outputs"
			}
			for _, want := range []string{"Code generated by infergen", "input " + inputs, "(" + outputs + ", error)", "Step(", "Finish("} {
				if !bytes.Contains(source, []byte(want)) {
					t.Fatalf("generated source does not contain %q:\n%s", want, source)
				}
			}
		})
	}
}

func TestCommandErrorsPreserveOutput(t *testing.T) {
	tests := []struct {
		name, config, want string
		args               []string
	}{
		{name: "missing rules", want: "rule files are required"},
		{name: "unknown flag", args: []string{"--unknown"}, want: "unknown flag"},
		{name: "positional argument", args: []string{"--rules", "rules.go", "extra.go"}, want: "unknown command"},
		{name: "missing explicit config", args: []string{"--config", "missing.yaml"}, want: "read config:"},
		{name: "malformed config", config: "rules: [", want: "read config:"},
		{name: "invalid config type", config: "rules: {file: rules.go}", want: "decode config:"},
		{name: "blank rule name", args: []string{"--rules", "rules.go, "}, want: "rule file names must not be empty"},
		{name: "missing rule file", args: []string{"--rules", "missing.go"}, want: "read ruleset package:"},
		{name: "invalid check value", config: "rules: [rules.go, extra.go]\ncheck: sometimes\n", want: "decode config:"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			commandFixture(t)
			if test.config != "" {
				write(t, "infergen.yaml", test.config)
			}
			const existing = "existing generated output\n"
			write(t, "zz_infergo_gen.go", existing)
			command := newCommand()
			command.SetArgs(append([]string{}, test.args...))
			err := command.Execute()
			if err == nil || !strings.Contains(err.Error(), test.want) {
				t.Fatalf("error = %v, want %q", err, test.want)
			}
			output, err := os.ReadFile("zz_infergo_gen.go")
			if err != nil || string(output) != existing {
				t.Fatalf("existing output changed: %q, error %v", output, err)
			}
		})
	}
}

func TestCheckMode(t *testing.T) {
	const rules = "rules.go,extra.go"
	triggers := []struct {
		name string
		args []string
		env  string
	}{
		{name: "flag", args: []string{"--rules", rules, "--check"}},
		{name: "environment", args: []string{"--rules", rules}, env: "true"},
	}
	states := []struct {
		name    string
		prepare func(t *testing.T)
		want    string
	}{
		{name: "current", prepare: func(*testing.T) {}},
		{
			// A parameter rename still compiles, so only check mode can report it.
			name: "stale",
			prepare: func(t *testing.T) {
				write(t, "extra.go", "package rules\nfunc Finish(seed int) (value int) { return seed + 1 }\n")
			},
			want: "example.com/rules: zz_infergo_gen.go is out of date; run go generate",
		},
		{
			name: "missing",
			prepare: func(t *testing.T) {
				if err := os.Remove("zz_infergo_gen.go"); err != nil {
					t.Fatal(err)
				}
			},
			want: "example.com/rules: zz_infergo_gen.go is missing; run go generate",
		},
	}
	for _, trigger := range triggers {
		for _, state := range states {
			t.Run(trigger.name+"/"+state.name, func(t *testing.T) {
				commandFixture(t)
				generate := newCommand()
				generate.SetArgs([]string{"--rules", rules})
				if err := generate.Execute(); err != nil {
					t.Fatal(err)
				}
				state.prepare(t)
				before, readErr := os.ReadFile("zz_infergo_gen.go")

				t.Setenv("INFERGEN_CHECK", trigger.env)
				command := newCommand()
				command.SetArgs(trigger.args)
				err := command.Execute()
				if state.want == "" && err != nil {
					t.Fatal(err)
				}
				if state.want != "" && (err == nil || !strings.Contains(err.Error(), state.want)) {
					t.Fatalf("error = %v, want %q", err, state.want)
				}

				after, afterErr := os.ReadFile("zz_infergo_gen.go")
				if !bytes.Equal(before, after) || (readErr == nil) != (afterErr == nil) {
					t.Fatalf("check mode wrote output: %q, error %v", after, afterErr)
				}
				temporary, err := filepath.Glob(".infergen-*")
				if err != nil || len(temporary) != 0 {
					t.Fatalf("check mode left temporary files: %v, error %v", temporary, err)
				}
			})
		}
	}
}

// execute runs the command and returns what it printed to standard error.
func execute(t *testing.T, args ...string) (string, error) {
	t.Helper()
	var stderr bytes.Buffer
	command := newCommand()
	command.SetErr(&stderr)
	command.SetArgs(args)
	err := command.Execute()
	return stderr.String(), err
}

func TestUpdateLine(t *testing.T) {
	commandFixture(t)
	args := []string{"--rules", "rules.go,extra.go"}
	const updated = "infergen: example.com/rules: updated zz_infergo_gen.go (2 rules)\n"
	if stderr, err := execute(t, args...); err != nil || stderr != updated {
		t.Fatalf("first run: %q, error %v", stderr, err)
	}
	first, err := os.Stat("zz_infergo_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	old := first.ModTime().Add(-time.Hour)
	if err := os.Chtimes("zz_infergo_gen.go", old, old); err != nil {
		t.Fatal(err)
	}
	if stderr, err := execute(t, args...); err != nil || stderr != "" {
		t.Fatalf("no-op run: %q, error %v", stderr, err)
	}
	second, err := os.Stat("zz_infergo_gen.go")
	if err != nil || !second.ModTime().Equal(old) {
		t.Fatalf("no-op run rewrote the file: %v, error %v", second.ModTime(), err)
	}
	// This rewires Finish to another int fact without changing a contract.
	write(t, "extra.go", "package rules\nfunc Finish(seed int) (value int) { return seed }\n")
	stderr, err := execute(t, args...)
	if err != nil || !strings.Contains(stderr, "infergen: example.com/rules: updated zz_infergo_gen.go (1 rule)\n") {
		t.Fatalf("rewiring run: %q, error %v", stderr, err)
	}
}

func TestWarningsKeepSuccessfulExit(t *testing.T) {
	commandFixture(t)
	args := []string{"--rules", "rules.go,extra.go"}
	write(t, "rules.go", `package rules
type Inputs struct {
    Seed int `+"`fact:\"seed\"`"+`
    Unused int `+"`fact:\"unused\"`"+`
}
type Outputs struct { Value int `+"`fact:\"value\"`"+` }
func Step(seed int) (middle int) { return seed + 1 }
func Orphan(seed int) (extra int) { return seed }
`)
	warnings := []string{
		`infergen: example.com/rules: warning: rules.go:4:5: input fact "unused" is not used by any output or retained rule`,
		"infergen: example.com/rules: warning: rules.go:8:6: rule Orphan is not needed by any output and was left out",
	}
	stderr, err := execute(t, args...)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range append(warnings, "infergen: example.com/rules: updated") {
		if !strings.Contains(stderr, want) {
			t.Errorf("generate output %q lacks %q", stderr, want)
		}
	}
	stderr, err = execute(t, append(args, "--check")...)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(stderr, "updated") {
		t.Errorf("check mode claimed an update: %q", stderr)
	}
	for _, want := range warnings {
		if !strings.Contains(stderr, want) {
			t.Errorf("check output %q lacks %q", stderr, want)
		}
	}
}

