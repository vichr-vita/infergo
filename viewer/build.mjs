import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

const output = new URL('viewer.js', import.meta.url);
const result = await build({
  entryPoints: [new URL('viewer.ts', import.meta.url).pathname],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  minify: true,
  legalComments: 'inline',
  write: false,
});
// Preserve the full licenses of code embedded in each exported HTML file.
const licenses = await Promise.all(['@dagrejs/dagre', '@dagrejs/graphlib'].map(async name => {
  const license = await readFile(new URL(`../node_modules/${name}/LICENSE`, import.meta.url), 'utf8');
  return `${name}\n${license}`;
}));
licenses.push(`Inferrum viewer, adapted for Infergo\n${await readFile(new URL('LICENSE-Inferrum.txt', import.meta.url), 'utf8')}`);
const bundle = `/* Generated by npm run build:viewer.\n${licenses.join('\n')}*/\n${result.outputFiles[0].text}`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== bundle) {
    throw new Error('Viewer bundle is stale. Run npm run build:viewer.');
  }
} else {
  await writeFile(output, bundle);
  console.log(`Built viewer.js (${bundle.length.toLocaleString()} bytes)`);
}
