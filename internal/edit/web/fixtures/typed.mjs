// Writes typed.ts, which embeds each fixture as a literal annotated with its
// protocol type, so tsc rejects a wrong key, a missing key, or a wrong enum
// value. A plain JSON import widens string literals to string, which would hide
// a wrong enum value. npm runs this as the precheck:editor hook. typed.ts is
// generated and ignored by git.
import { readFileSync, writeFileSync } from 'node:fs';

const directory = new URL('.', import.meta.url);
const fixtures = [
  ['model', 'Model'],
  ['check', 'Check'],
  ['values', 'Values'],
  ['history', 'History'],
];
let source = `// Generated by typed.mjs from the JSON files next to it. Do not edit or commit.\nimport type { ${fixtures.map(([, type]) => type).join(', ')} } from '../src/protocol';\n`;
for (const [name, type] of fixtures) {
  const json = JSON.stringify(JSON.parse(readFileSync(new URL(`${name}.json`, directory), 'utf8')), null, 2);
  source += `\nexport const ${name}: ${type} = ${json};\n`;
}
writeFileSync(new URL('typed.ts', directory), source);
