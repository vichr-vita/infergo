// Builds the editor page's assets. Run through npm (see package.json):
//
//   node build.mjs           editor.js and editor.css, minified, checked in
//   node build.mjs --check   fails when the committed editor.js or editor.css is stale
//   node build.mjs --dev     dev/ (gitignored): unminified bundle on the mock Api, plus index.html
//   node build.mjs --dev --watch   the same, rebuilt whenever src/ or editor.html changes
//   node build.mjs --test    bundles src/**/*.test.ts for Node and runs them with node --test
//
// editor.js bundles src/boot.ts. Its header carries the full licence of every
// third-party package that ends up in the bundle, read from the esbuild
// metafile plus those packages' runtime dependencies, so adding CodeMirror or
// dagre needs no change here.
//
// editor.css is src/shell.css followed by every src/<region>/**/*.css in path
// order. A region adds styles by adding a .css file to its own directory.
import { build } from 'esbuild';
import { spawnSync } from 'node:child_process';
import { existsSync, watch } from 'node:fs';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = dirname(fileURLToPath(import.meta.url));
const repository = join(web, '../../..');
const source = join(web, 'src');
const args = new Set(process.argv.slice(2));

// Every file under a directory, recursively, in a stable order.
async function files(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const found = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) found.push(...await files(path));
    else found.push(path);
  }
  return found;
}

async function bundleScript(entry, { minify }) {
  const result = await build({
    entryPoints: [join(source, entry)],
    absWorkingDir: web,
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    minify,
    sourcemap: minify ? false : 'inline',
    legalComments: 'inline',
    metafile: true,
    write: false,
    logLevel: 'warning',
  });
  return { text: result.outputFiles[0].text, inputs: Object.keys(result.metafile.inputs) };
}

// The licence text of each npm package in the bundle, and the Inferrum licence
// when the bundle uses the viewer's code (navigation.ts).
async function licenceHeader(inputs, label) {
  const packages = new Set();
  for (const input of inputs) {
    const match = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
    if (match) packages.add(match[1]);
  }
  // A package may ship a dist with its dependencies already inlined, as dagre
  // does with graphlib, so the metafile cannot see them. Add every runtime
  // dependency of a bundled package, transitively.
  for (const name of packages) {
    const manifest = JSON.parse(await readFile(join(repository, 'node_modules', name, 'package.json'), 'utf8'));
    for (const dependency of Object.keys(manifest.dependencies ?? {})) packages.add(dependency);
  }
  const sections = [];
  for (const name of [...packages].sort()) {
    const directory = join(repository, 'node_modules', name);
    const file = (await readdir(directory)).find(entry => /^licen[cs]e(\.(md|txt))?$/i.test(entry));
    if (!file) throw new Error(`${name} is in the editor bundle but ships no LICENSE file. Add its licence by hand.`);
    sections.push(`${name}\n${await readFile(join(directory, file), 'utf8')}`);
  }
  if (inputs.some(input => input.includes('viewer/'))) {
    sections.push(`Inferrum viewer, adapted for Infergo\n${await readFile(join(repository, 'viewer/LICENSE-Inferrum.txt'), 'utf8')}`);
  }
  const body = sections.length ? `\n${sections.join('\n')}` : '\nNo third-party code.\n';
  return `/* Generated by ${label}.${body}*/\n`;
}

async function stylesheet({ minify, label }) {
  const regions = (await files(source)).filter(path => path.endsWith('.css') && dirname(path) !== source).sort();
  const parts = [join(source, 'shell.css'), ...regions];
  const css = (await Promise.all(parts.map(async path => `/* ${relative(web, path)} */\n${await readFile(path, 'utf8')}`))).join('\n');
  if (!minify) return css;
  const result = await build({ stdin: { contents: css, loader: 'css', resolveDir: source }, minify: true, write: false, logLevel: 'warning' });
  return `/* Generated by ${label} from ${parts.map(path => relative(web, path)).join(', ')}. */\n${result.outputFiles[0].text}`;
}

async function shipped() {
  const label = 'npm run build:editor';
  const script = await bundleScript('boot.ts', { minify: true });
  const leaked = script.inputs.filter(input => /src\/(mock|dev)\.ts$|fixtures\//.test(input));
  if (leaked.length) throw new Error(`The shipped bundle must not contain the mock or fixtures: ${leaked.join(', ')}`);
  return {
    'editor.js': `${await licenceHeader(script.inputs, label)}${script.text}`,
    'editor.css': await stylesheet({ minify: true, label }),
  };
}

async function development() {
  const started = Date.now();
  const script = await bundleScript('dev.ts', { minify: false });
  const output = join(web, 'dev');
  await mkdir(output, { recursive: true });
  const page = (await readFile(join(web, 'editor.html'), 'utf8')).replace('<title>Infergo editor</title>', '<title>Infergo editor (mock)</title>');
  await writeFile(join(output, 'index.html'), page);
  await writeFile(join(output, 'editor.js'), script.text);
  await writeFile(join(output, 'editor.css'), await stylesheet({ minify: false }));
  console.log(`Built ${relative(repository, output)}/index.html on the mock Api in ${Date.now() - started} ms`);
}

async function test() {
  const tests = (await files(source)).filter(path => path.endsWith('.test.ts'));
  const output = join(web, '.test');
  await rm(output, { recursive: true, force: true });
  await build({
    entryPoints: tests,
    absWorkingDir: web,
    outdir: output,
    outbase: source,
    outExtension: { '.js': '.mjs' },
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: ['node22'],
    sourcemap: 'inline',
    logLevel: 'warning',
  });
  const compiled = (await files(output)).filter(path => path.endsWith('.test.mjs'));
  const run = spawnSync(process.execPath, ['--enable-source-maps', '--test', ...compiled], { stdio: 'inherit' });
  process.exitCode = run.status ?? 1;
}

if (args.has('--test')) {
  await test();
} else if (args.has('--dev')) {
  await development();
  if (args.has('--watch')) {
    let timer;
    const rebuild = () => {
      clearTimeout(timer);
      timer = setTimeout(() => development().catch(error => console.error(error.message)), 50);
    };
    watch(source, { recursive: true }, rebuild);
    watch(join(web, 'editor.html'), rebuild);
    console.log('Watching src/ and editor.html. Ctrl+C stops.');
  }
} else {
  const built = await shipped();
  if (args.has('--check')) {
    const stale = [];
    for (const [name, content] of Object.entries(built)) {
      const path = join(web, name);
      if (!existsSync(path) || await readFile(path, 'utf8') !== content) stale.push(name);
    }
    if (stale.length) throw new Error(`Editor bundle is stale: ${stale.join(', ')}. Run npm run build:editor.`);
  } else {
    for (const [name, content] of Object.entries(built)) {
      await writeFile(join(web, name), content);
      console.log(`Built ${name} (${content.length.toLocaleString()} bytes)`);
    }
  }
}
